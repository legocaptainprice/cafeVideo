-- Import into an empty PostgreSQL 13+ database.
-- User/account data is intentionally not seeded, only application reference data is.

CREATE TABLE accounts (
    userID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) UNIQUE,
    password TEXT,
    email VARCHAR(320),
    accountStanding VARCHAR(32),
    verification VARCHAR(255)
);

CREATE TABLE profileColorSets (
    profileSetID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profileSetName VARCHAR(100),
    profileBorderColor VARCHAR(32),
    profileHeaderColor VARCHAR(32),
    profilePictureBorderColor VARCHAR(32)
);

CREATE TABLE roles (
    roleID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roleName VARCHAR(100)
);

CREATE TABLE events (
    eventID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventName VARCHAR(100),
    eventCSSDir TEXT,
    eventHTMLDir TEXT,
    eventImagesDir TEXT,
    eventJSDir TEXT
);

CREATE TABLE feature_gating (
    featureID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    featureName VARCHAR(100),
    description TEXT,
    enabled SMALLINT
);

CREATE TABLE season (
    eventState SMALLINT,
    eventID BIGINT REFERENCES events(eventID)
);

CREATE TABLE profiles (
    userID BIGINT REFERENCES accounts(userID),
    displayName VARCHAR(255),
    profileBio TEXT,
    profilePicture VARCHAR(255),
    profileBanner VARCHAR(255),
    profileColorTheme BIGINT REFERENCES profileColorSets(profileSetID),
    joinDate VARCHAR(32),
    channelURLEnabled SMALLINT,
    channelURL VARCHAR(255)
);

CREATE TABLE videos (
    videoID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userID BIGINT REFERENCES accounts(userID),
    videoTitle VARCHAR(255),
    videoDescription TEXT,
    videoTags TEXT,
    videoFile VARCHAR(255),
    datetime BIGINT,
    views BIGINT DEFAULT 0,
    videoThumbnail VARCHAR(255)
);

CREATE TABLE blogs (
    blogID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userID BIGINT REFERENCES accounts(userID),
    blogTitle VARCHAR(255),
    blogDescription TEXT,
    blogContent TEXT,
    blogDatetime BIGINT
);

CREATE TABLE comments (
    commentID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    videoID BIGINT REFERENCES videos(videoID),
    userID BIGINT REFERENCES accounts(userID),
    comment TEXT
);

CREATE TABLE replies (
    replyID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commentID BIGINT REFERENCES comments(commentID),
    userID BIGINT REFERENCES accounts(userID),
    reply TEXT
);

CREATE TABLE playlists (
    playlistID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userID BIGINT REFERENCES accounts(userID) ON DELETE CASCADE,
    playlistName VARCHAR(255),
    playlistDescription TEXT,
    playlistType VARCHAR(64),
    visibilityType VARCHAR(32)
);

CREATE TABLE playlist_contents (
    playlistID BIGINT NOT NULL REFERENCES playlists(playlistID) ON DELETE CASCADE,
    videoID BIGINT NOT NULL REFERENCES videos(videoID) ON DELETE CASCADE,
    PRIMARY KEY (playlistID, videoID)
);

CREATE TABLE feature_access (
    featureID BIGINT REFERENCES feature_gating(featureID),
    userID BIGINT REFERENCES accounts(userID)
);

CREATE TABLE user_roles (
    userID BIGINT REFERENCES accounts(userID),
    roleID BIGINT REFERENCES roles(roleID)
);

CREATE TABLE subscriptions (
    userID BIGINT REFERENCES accounts(userID),
    subscribedToUserID BIGINT REFERENCES accounts(userID)
);

CREATE TABLE likedVideos (
    videoID BIGINT REFERENCES videos(videoID) ON DELETE CASCADE,
    creatorID BIGINT REFERENCES accounts(userID) ON DELETE CASCADE,
    userID BIGINT REFERENCES accounts(userID) ON DELETE CASCADE
);

CREATE TABLE likedComments (
    commentID BIGINT REFERENCES comments(commentID) ON DELETE CASCADE,
    commenterID BIGINT REFERENCES accounts(userID) ON DELETE CASCADE,
    userID BIGINT REFERENCES accounts(userID) ON DELETE CASCADE
);

CREATE TABLE likedReplies (
    replyID BIGINT REFERENCES replies(replyID) ON DELETE CASCADE,
    replierID BIGINT REFERENCES accounts(userID) ON DELETE CASCADE,
    userID BIGINT REFERENCES accounts(userID) ON DELETE CASCADE
);

CREATE TABLE notifications (
    notificationID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notificationRecipientID BIGINT REFERENCES accounts(userID) ON DELETE CASCADE,
    notificationSenderID BIGINT REFERENCES accounts(userID) ON DELETE CASCADE,
    notificationTitle VARCHAR(255),
    notificationDescription TEXT,
    notificationDateTime BIGINT,
    notificationItem VARCHAR(255),
    notificationImage VARCHAR(255),
    notificationRead SMALLINT
);

CREATE TABLE watchHistory (
    userID BIGINT NOT NULL REFERENCES accounts(userID) ON DELETE CASCADE,
    videoID BIGINT NOT NULL REFERENCES videos(videoID) ON DELETE CASCADE,
    historyDateTime BIGINT,
    PRIMARY KEY (userID, videoID)
);

CREATE TABLE cafeCorners (
    cornerID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userID BIGINT NOT NULL REFERENCES accounts(userID) ON DELETE CASCADE,
    cornerName VARCHAR(255),
    cornerDescription TEXT,
    cornerBanner VARCHAR(255),
    cornerColorTheme BIGINT REFERENCES profileColorSets(profileSetID) ON DELETE SET NULL,
    cornerURLEnabled SMALLINT,
    cornerURL VARCHAR(255),
    creationDate BIGINT
);

CREATE TABLE cafeCornerMembers (
    cornerID BIGINT NOT NULL REFERENCES cafeCorners(cornerID) ON DELETE CASCADE,
    userID BIGINT NOT NULL REFERENCES accounts(userID) ON DELETE CASCADE,
    role VARCHAR(32) NOT NULL,
    joinedDate BIGINT,
    PRIMARY KEY (cornerID, userID)
);

CREATE TABLE cornerInvitations (
    invitationID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cornerID BIGINT NOT NULL REFERENCES cafeCorners(cornerID) ON DELETE CASCADE,
    inviterUserID BIGINT NOT NULL REFERENCES accounts(userID) ON DELETE CASCADE,
    invitedUserID BIGINT NOT NULL REFERENCES accounts(userID) ON DELETE CASCADE,
    invitationStatus VARCHAR(32) NOT NULL DEFAULT 'pending',
    createdAt BIGINT NOT NULL
);

